CREATE POLICY "Service role has full access to articles" ON articles
    FOR ALL USING (auth.role() = 'service_role');

CREATE POLICY "Service role has full access to article_contexts" ON article_contexts
    FOR ALL USING (auth.role() = 'service_role');

CREATE POLICY "Service role has full access to user_profiles" ON user_profiles
    FOR ALL USING (auth.role() = 'service_role');

CREATE POLICY "Service role has full access to user_interactions" ON user_interactions
    FOR ALL USING (auth.role() = 'service_role');

CREATE POLICY "Service role has full access to chat_history" ON chat_history
    FOR ALL USING (auth.role() = 'service_role');
